/* Landing Page Course Search - which landing sites sell which courses.
   Data globals come from assets/data.js (generated by tools/course-search/build_landing_pages.py in subdomains.hazwoperosha.us):
   SITES, COURSES, OFFERS, SITE_GROUPS, TOPICS, CATEGORIES, BUILT_ON. */
(function () {
  "use strict";

  var VIEW_KEY = "lpcs_view_mode_v1";
  var MODE_KEY = "lpcs_search_mode_v1";

  var SORT_OPTIONS = {
    courses: [
      ["sites:desc", "Most sites first"],
      ["sites:asc", "Fewest sites first"],
      ["name:asc", "Name (A-Z)"],
      ["name:desc", "Name (Z-A)"],
      ["price:asc", "Price: Low to High"],
      ["price:desc", "Price: High to Low"],
    ],
    sites: [
      ["name:asc", "Site (A-Z)"],
      ["name:desc", "Site (Z-A)"],
      ["courses:desc", "Most courses first"],
      ["courses:asc", "Fewest courses first"],
    ],
  };

  var state = {
    mode: "courses",
    view: "list",
    sort: { courses: "sites:desc", sites: "name:asc" },
  };
  var els = {};

  // ------------------------------------------------------------ indexes
  var siteById = {};
  var courseById = {};
  var offersByCourse = {};
  var offersBySite = {};

  function buildIndexes() {
    SITES.forEach(function (s) {
      siteById[s.id] = s;
      offersBySite[s.id] = [];
    });
    COURSES.forEach(function (c) {
      courseById[c.id] = c;
      offersByCourse[c.id] = [];
    });
    OFFERS.forEach(function (o) {
      offersByCourse[o.courseId].push(o);
      offersBySite[o.siteId].push(o);
    });
  }

  // ------------------------------------------------------------ utils
  function esc(s) {
    return String(s == null ? "" : s)
      .replace(/&/g, "&amp;")
      .replace(/</g, "&lt;")
      .replace(/>/g, "&gt;")
      .replace(/"/g, "&quot;");
  }

  function highlight(text, q) {
    var t = String(text == null ? "" : text);
    if (!q) return esc(t);
    var i = t.toLowerCase().indexOf(q.toLowerCase());
    if (i < 0) return esc(t);
    return esc(t.slice(0, i)) + "<mark>" + esc(t.slice(i, i + q.length)) + "</mark>" + esc(t.slice(i + q.length));
  }

  function fmtMoney(n) {
    if (n == null || isNaN(Number(n))) return "-";
    return "$" + Number(n).toLocaleString("en-US", { minimumFractionDigits: 2, maximumFractionDigits: 2 });
  }

  function priceRange(c) {
    if (c.priceMin == null) return "-";
    if (c.priceMin === c.priceMax) return fmtMoney(c.priceMin);
    return fmtMoney(c.priceMin) + " - " + fmtMoney(c.priceMax);
  }

  function plural(n, one, many) {
    return n + " " + (n === 1 ? one : many);
  }

  function shortHost(id) {
    return id.replace(/\.hazwoperosha\.us$/, ".hazwoperosha.us");
  }

  function store(key, val) {
    try {
      if (val === undefined) return localStorage.getItem(key);
      localStorage.setItem(key, val);
    } catch (e) {
      return null;
    }
  }

  // ------------------------------------------------------------ filters
  function readFilters() {
    return {
      q: els.search.value.trim(),
      site: els.site.value,
      course: els.course.value === "" ? null : Number(els.course.value),
      group: els.group.value,
      topic: els.topic.value,
      category: els.category.value,
    };
  }

  function siteMatchesGroupTopic(s, f) {
    return (!f.group || s.group === f.group) && (!f.topic || s.topic === f.topic);
  }

  function courseText(c) {
    return [c.name, c.altNames.join(" "), c.category, c.citation].join(" ").toLowerCase();
  }

  function siteText(s) {
    return [s.id, s.name, s.topic, s.group].join(" ").toLowerCase();
  }

  // Offers that survive the sidebar filters (not the search box).
  function offerPasses(o, f) {
    var s = siteById[o.siteId];
    var c = courseById[o.courseId];
    if (f.site && o.siteId !== f.site) return false;
    if (f.course != null && o.courseId !== f.course) return false;
    if (!siteMatchesGroupTopic(s, f)) return false;
    if (f.category && c.category !== f.category) return false;
    return true;
  }

  function sidebarActive(f) {
    return !!(f.site || f.course != null || f.group || f.topic || f.category);
  }

  function filterCourses(f) {
    var q = f.q.toLowerCase();
    var active = sidebarActive(f);
    return COURSES.filter(function (c) {
      if (q && courseText(c).indexOf(q) < 0) return false;
      if (!active) return true;
      return offersByCourse[c.id].some(function (o) {
        return offerPasses(o, f);
      });
    });
  }

  function filterSites(f) {
    var q = f.q.toLowerCase();
    return SITES.filter(function (s) {
      if (f.site && s.id !== f.site) return false;
      if (!siteMatchesGroupTopic(s, f)) return false;
      var offers = offersBySite[s.id];
      if (f.course != null || f.category) {
        var ok = offers.some(function (o) {
          return offerPasses(o, f);
        });
        if (!ok) return false;
      }
      if (q) {
        if (siteText(s).indexOf(q) >= 0) return true;
        return offers.some(function (o) {
          return courseText(courseById[o.courseId]).indexOf(q) >= 0 || o.name.toLowerCase().indexOf(q) >= 0;
        });
      }
      return true;
    });
  }

  // ------------------------------------------------------------ sorting
  function cmp(a, b, dir) {
    if (a == null && b == null) return 0;
    if (a == null) return 1;
    if (b == null) return -1;
    var r = typeof a === "string" ? a.localeCompare(b) : a - b;
    return dir === "desc" ? -r : r;
  }

  function sortRows(rows) {
    var parts = state.sort[state.mode].split(":");
    var key = parts[0];
    var dir = parts[1];
    return rows.slice().sort(function (a, b) {
      var r;
      if (state.mode === "courses") {
        if (key === "sites") r = cmp(a.siteCount, b.siteCount, dir);
        else if (key === "price") r = cmp(a.priceMin, b.priceMin, dir);
        else r = cmp(a.name.toLowerCase(), b.name.toLowerCase(), dir);
        return r || a.name.localeCompare(b.name);
      }
      if (key === "courses") r = cmp(a.courseCount, b.courseCount, dir);
      else r = cmp(a.id, b.id, dir);
      return r || a.id.localeCompare(b.id);
    });
  }

  // ------------------------------------------------------------ rendering helpers
  function siteLink(s, q) {
    return '<a href="' + esc(s.url) + '" target="_blank" rel="noopener" class="site-link">' + highlight(shortHost(s.id), q) + "</a>";
  }

  function groupPill(s) {
    var cls = s.group === "Main domains" ? "pill pill-accent" : "pill";
    return '<span class="' + cls + '">' + esc(s.group === "Main domains" ? "Main domain" : "Subdomain") + "</span>";
  }

  // Sites offering a course, honoring group/topic/site filters, as a list of rows.
  function courseSitesHtml(c, f) {
    var offers = offersByCourse[c.id].slice().sort(function (a, b) {
      var sa = siteById[a.siteId];
      var sb = siteById[b.siteId];
      if (sa.group !== sb.group) return sa.group === "Main domains" ? -1 : 1;
      return a.siteId.localeCompare(b.siteId);
    });
    var rows = offers.map(function (o) {
      var s = siteById[o.siteId];
      var dim = f && (f.site || f.group || f.topic) && !offerPasses(o, { site: f.site, group: f.group, topic: f.topic, course: null, category: "" });
      return (
        '<div class="offer-row' + (dim ? " dim" : "") + '">' +
        '<div class="offer-main">' + siteLink(s) + " " + groupPill(s) + (s.topic ? ' <span class="pill">' + esc(s.topic) + "</span>" : "") + "</div>" +
        '<div class="offer-meta">' +
        (o.name !== c.name ? '<span class="offer-alt" title="Name used on this site">"' + esc(o.name) + '"</span>' : "") +
        "<span>" + fmtMoney(o.price) + "</span>" +
        (o.url ? '<a href="' + esc(o.url) + '" target="_blank" rel="noopener">Course page ↗</a>' : "") +
        "</div></div>"
      );
    });
    return '<div class="offer-list">' + rows.join("") + "</div>";
  }

  function courseDetailHtml(c, f) {
    var fields = [
      ["Category", c.category || "-"],
      ["Duration", c.duration || "-"],
      ["Price", priceRange(c)],
      ["Citation / Standard", c.citation || "-"],
      ["Sites", c.siteCount],
    ];
    var grid = '<div class="detail-grid">' + fields.map(function (x) {
      return '<div><div class="label">' + esc(x[0]) + '</div><div class="value">' + esc(x[1]) + "</div></div>";
    }).join("") + "</div>";
    if (c.altNames.length) {
      grid += '<div class="modal-section-title">Also listed as</div><div class="row-tags">' + c.altNames.map(function (n) {
        return '<span class="pill">' + esc(n) + "</span>";
      }).join("") + "</div>";
    }
    return grid + '<div class="modal-section-title">Sold on ' + plural(c.siteCount, "site", "sites") + "</div>" + courseSitesHtml(c, f);
  }

  function siteDetailEl(s, f) {
    var q = f.q.toLowerCase();
    var wrap = document.createElement("div");
    var fields = [
      ["URL", '<a href="' + esc(s.url) + '" target="_blank" rel="noopener">' + esc(s.url) + "</a>"],
      ["Group", esc(s.group)],
      ["Topic", esc(s.topic || "-")],
      ["Data source", esc(s.source)],
    ];
    wrap.innerHTML =
      '<div class="site-title">' + esc(s.name) + "</div>" +
      '<div class="detail-grid">' + fields.map(function (x) {
        return '<div><div class="label">' + x[0] + '</div><div class="value">' + x[1] + "</div></div>";
      }).join("") + "</div>" +
      '<div class="modal-section-title">' + plural(s.courseCount, "course", "courses") + " on this site</div>";
    var list = document.createElement("div");
    list.className = "bundle-course-list";
    var offers = offersBySite[s.id].slice().sort(function (a, b) {
      return a.name.localeCompare(b.name);
    });
    if (!offers.length) {
      list.innerHTML = '<div class="muted">No paid course pages found on this site.</div>';
    }
    offers.forEach(function (o) {
      var c = courseById[o.courseId];
      var hit = q && (courseText(c).indexOf(q) >= 0 || o.name.toLowerCase().indexOf(q) >= 0);
      var item = document.createElement("div");
      item.className = "bundle-course-item" + (hit ? " hit" : "") + (f.course === c.id ? " hit" : "");
      item.innerHTML =
        '<div class="bundle-course-name">' + highlight(o.name, f.q) + "</div>" +
        '<div class="bundle-course-meta">' +
        (c.category ? '<span class="pill">' + esc(c.category) + "</span>" : "") +
        "<span>" + fmtMoney(o.price) + "</span>" +
        '<span class="muted">on ' + plural(c.siteCount, "site", "sites") + "</span>" +
        (o.url ? '<a href="' + esc(o.url) + '" target="_blank" rel="noopener">Course page ↗</a>' : "") +
        "</div>";
      item.querySelector("a") && item.querySelectorAll("a").forEach(function (a) {
        a.addEventListener("click", function (e) {
          e.stopPropagation();
        });
      });
      item.addEventListener("click", function (e) {
        e.stopPropagation();
        openModal(c.name, courseDetailHtml(c, null));
      });
      list.appendChild(item);
    });
    wrap.appendChild(list);
    return wrap;
  }

  // ------------------------------------------------------------ render
  function render() {
    var f = readFilters();
    var rows = state.mode === "courses" ? filterCourses(f) : filterSites(f);
    rows = sortRows(rows);
    state.lastRows = rows;
    state.lastFilters = f;

    var noun = state.mode === "courses" ? ["course", "courses"] : ["site", "sites"];
    els.count.innerHTML = "<strong>" + rows.length + "</strong> " + (rows.length === 1 ? noun[0] : noun[1]) + " found";
    renderActiveFilters(f);
    writeUrl(f);

    els.body.innerHTML = "";
    els.grid.innerHTML = "";
    els.empty.hidden = rows.length > 0;
    els.wrap.hidden = rows.length === 0;

    if (state.mode === "courses") {
      els.head.innerHTML = "<tr><th>Course</th><th>Category</th><th>Duration</th><th>Price</th><th>Sites</th></tr>";
    } else {
      els.head.innerHTML = "<tr><th>Site</th><th>Group</th><th>Topic</th><th>Courses</th></tr>";
    }

    var isList = state.view === "list";
    els.body.parentNode.hidden = !isList;
    els.grid.hidden = isList;

    var frag = document.createDocumentFragment();
    rows.forEach(function (r) {
      if (state.mode === "courses") {
        if (isList) buildCourseRow(r, f, frag);
        else frag.appendChild(buildCourseCard(r, f));
      } else {
        if (isList) buildSiteRow(r, f, frag);
        else frag.appendChild(buildSiteCard(r, f));
      }
    });
    (isList ? els.body : els.grid).appendChild(frag);
  }

  function countMatching(c, f) {
    if (!(f.site || f.group || f.topic)) return null;
    return offersByCourse[c.id].filter(function (o) {
      return offerPasses(o, { site: f.site, group: f.group, topic: f.topic, course: null, category: "" });
    }).length;
  }

  function sitesCell(c, f) {
    var m = countMatching(c, f);
    return m == null || m === c.siteCount ? String(c.siteCount) : m + " of " + c.siteCount;
  }

  function buildCourseRow(c, f, frag) {
    var tr = document.createElement("tr");
    tr.innerHTML =
      '<td class="course-name-cell" data-label="Course">' + highlight(c.name, f.q) +
      (c.altNames.length ? '<div class="row-tags"><span class="pill" title="' + esc(c.altNames.join(" | ")) + '">+' + c.altNames.length + " alt. name" + (c.altNames.length > 1 ? "s" : "") + "</span></div>" : "") +
      "</td>" +
      '<td data-label="Category">' + esc(c.category || "-") + "</td>" +
      '<td data-label="Duration">' + esc(c.duration || "-") + "</td>" +
      '<td class="msrp-cell" data-label="Price">' + esc(priceRange(c)) + "</td>" +
      '<td data-label="Sites"><span class="count-badge">' + esc(sitesCell(c, f)) + "</span></td>";
    var detail = document.createElement("tr");
    detail.className = "detail-row";
    detail.hidden = true;
    detail.innerHTML = '<td colspan="5"></td>';
    tr.addEventListener("click", function (e) {
      if (e.target.closest("a")) return;
      if (detail.hidden) detail.firstChild.innerHTML = courseDetailHtml(c, f);
      detail.hidden = !detail.hidden;
    });
    frag.appendChild(tr);
    frag.appendChild(detail);
  }

  function buildCourseCard(c, f) {
    var d = document.createElement("div");
    d.className = "course-card";
    d.innerHTML =
      '<div class="card-name">' + highlight(c.name, f.q) + "</div>" +
      '<div class="card-pills">' + (c.category ? '<span class="pill">' + esc(c.category) + "</span>" : "") +
      (c.duration ? '<span class="pill">' + esc(c.duration) + "</span>" : "") + "</div>" +
      '<div class="card-meta-row"><span>' + esc(priceRange(c)) + '</span><span class="count-badge">' + esc(sitesCell(c, f)) + " site" + (c.siteCount === 1 ? "" : "s") + "</span></div>";
    d.addEventListener("click", function (e) {
      if (e.target.closest("a")) return;
      openModal(c.name, courseDetailHtml(c, f));
    });
    return d;
  }

  function buildSiteRow(s, f, frag) {
    var tr = document.createElement("tr");
    tr.innerHTML =
      '<td class="course-name-cell" data-label="Site">' + siteLink(s, f.q) + '<div class="row-sub">' + esc(s.name) + "</div></td>" +
      '<td data-label="Group">' + groupPill(s) + "</td>" +
      '<td data-label="Topic">' + esc(s.topic || "-") + "</td>" +
      '<td data-label="Courses"><span class="count-badge' + (s.courseCount ? "" : " zero") + '">' + s.courseCount + "</span></td>";
    var detail = document.createElement("tr");
    detail.className = "detail-row";
    detail.hidden = true;
    var td = document.createElement("td");
    td.colSpan = 4;
    detail.appendChild(td);
    tr.addEventListener("click", function (e) {
      if (e.target.closest("a")) return;
      if (detail.hidden) {
        td.innerHTML = "";
        td.appendChild(siteDetailEl(s, f));
      }
      detail.hidden = !detail.hidden;
    });
    frag.appendChild(tr);
    frag.appendChild(detail);
  }

  function buildSiteCard(s, f) {
    var d = document.createElement("div");
    d.className = "course-card";
    d.innerHTML =
      '<div class="card-name">' + siteLink(s, f.q) + "</div>" +
      '<div class="card-industries">' + esc(s.name) + "</div>" +
      '<div class="card-pills">' + groupPill(s) + (s.topic ? '<span class="pill">' + esc(s.topic) + "</span>" : "") + "</div>" +
      '<div class="card-meta-row"><span>' + plural(s.courseCount, "course", "courses") + "</span></div>";
    d.addEventListener("click", function (e) {
      if (e.target.closest("a")) return;
      openModal(shortHost(s.id), siteDetailEl(s, f));
    });
    return d;
  }

  function renderActiveFilters(f) {
    var chips = [];
    if (f.site) chips.push(["Site", f.site, "site"]);
    if (f.course != null) chips.push(["Course", courseById[f.course].name, "course"]);
    if (f.group) chips.push(["Group", f.group, "group"]);
    if (f.topic) chips.push(["Topic", f.topic, "topic"]);
    if (f.category) chips.push(["Category", f.category, "category"]);
    els.chips.hidden = !chips.length;
    els.chips.innerHTML = chips.map(function (c) {
      return '<button type="button" class="chip" data-key="' + c[2] + '">' + esc(c[0]) + ": " + esc(c[1]) + " <span aria-hidden=\"true\">×</span></button>";
    }).join("");
  }

  // ------------------------------------------------------------ modal
  function openModal(title, body) {
    els.modalTitle.textContent = title;
    els.modalBody.innerHTML = "";
    if (typeof body === "string") els.modalBody.innerHTML = body;
    else els.modalBody.appendChild(body);
    els.overlay.hidden = false;
  }

  function closeModal() {
    els.overlay.hidden = true;
  }

  // ------------------------------------------------------------ CSV
  function exportCsv() {
    var f = state.lastFilters;
    var rows = state.lastRows || [];
    var lines = [["Site", "Site group", "Site topic", "Course", "Name on site", "Category", "Duration", "Price", "Course page"]];
    var seen = {};
    rows.forEach(function (r) {
      var offers = state.mode === "courses" ? offersByCourse[r.id] : offersBySite[r.id];
      offers.forEach(function (o) {
        var key = o.siteId + "|" + o.courseId + "|" + o.url;
        if (seen[key]) return;
        if (state.mode === "courses" && (f.site || f.group || f.topic) && !offerPasses(o, { site: f.site, group: f.group, topic: f.topic, course: null, category: "" })) return;
        if (state.mode === "sites" && (f.course != null || f.category) && !offerPasses(o, f)) return;
        seen[key] = 1;
        var s = siteById[o.siteId];
        var c = courseById[o.courseId];
        lines.push([s.id, s.group, s.topic, c.name, o.name, c.category || "", o.duration || c.duration || "", o.price == null ? "" : o.price, o.url || ""]);
      });
    });
    var csv = lines.map(function (l) {
      return l.map(function (v) {
        v = String(v == null ? "" : v);
        return /[",\n]/.test(v) ? '"' + v.replace(/"/g, '""') + '"' : v;
      }).join(",");
    }).join("\n");
    var a = document.createElement("a");
    a.href = URL.createObjectURL(new Blob([csv], { type: "text/csv" }));
    a.download = "landing-page-courses-" + state.mode + ".csv";
    document.body.appendChild(a);
    a.click();
    a.remove();
  }

  // ------------------------------------------------------------ URL state
  function writeUrl(f) {
    var p = new URLSearchParams();
    if (state.mode !== "courses") p.set("mode", state.mode);
    if (f.q) p.set("q", f.q);
    if (f.site) p.set("site", f.site);
    if (f.course != null) p.set("course", courseById[f.course].name);
    if (f.group) p.set("group", f.group);
    if (f.topic) p.set("topic", f.topic);
    if (f.category) p.set("category", f.category);
    var qs = p.toString();
    try {
      history.replaceState(null, "", qs ? "?" + qs : location.pathname);
    } catch (e) {
      /* file:// or sandboxed */
    }
  }

  function readUrl() {
    var p = new URLSearchParams(location.search);
    if (p.get("mode") === "sites" || p.get("mode") === "courses") state.mode = p.get("mode");
    if (p.get("q")) els.search.value = p.get("q");
    setSelect(els.site, p.get("site"));
    setSelect(els.group, p.get("group"));
    setSelect(els.topic, p.get("topic"));
    setSelect(els.category, p.get("category"));
    var cname = p.get("course");
    if (cname) {
      var c = COURSES.find(function (x) {
        return x.name === cname;
      });
      if (c) els.course.value = String(c.id);
    }
  }

  function setSelect(sel, v) {
    if (!v) return;
    for (var i = 0; i < sel.options.length; i++) {
      if (sel.options[i].value === v) {
        sel.value = v;
        return;
      }
    }
  }

  // ------------------------------------------------------------ setup
  function option(value, label) {
    var o = document.createElement("option");
    o.value = value;
    o.textContent = label;
    return o;
  }

  function populateSelects() {
    els.site.appendChild(option("", "All sites (" + SITES.length + ")"));
    SITE_GROUPS.forEach(function (g) {
      var og = document.createElement("optgroup");
      og.label = g;
      SITES.filter(function (s) {
        return s.group === g;
      }).sort(function (a, b) {
        return a.id.localeCompare(b.id);
      }).forEach(function (s) {
        og.appendChild(option(s.id, shortHost(s.id) + " (" + s.courseCount + ")"));
      });
      els.site.appendChild(og);
    });

    els.course.appendChild(option("", "All courses (" + COURSES.length + ")"));
    COURSES.slice().sort(function (a, b) {
      return a.name.localeCompare(b.name);
    }).forEach(function (c) {
      els.course.appendChild(option(String(c.id), c.name + " (" + c.siteCount + ")"));
    });

    els.group.appendChild(option("", "All groups"));
    SITE_GROUPS.forEach(function (g) {
      els.group.appendChild(option(g, g));
    });
    els.topic.appendChild(option("", "All topics"));
    TOPICS.forEach(function (t) {
      els.topic.appendChild(option(t, t));
    });
    els.category.appendChild(option("", "All categories"));
    CATEGORIES.forEach(function (c) {
      els.category.appendChild(option(c, c));
    });
  }

  function populateSort() {
    els.sort.innerHTML = "";
    SORT_OPTIONS[state.mode].forEach(function (o) {
      els.sort.appendChild(option(o[0], o[1]));
    });
    els.sort.value = state.sort[state.mode];
  }

  function setMode(m) {
    state.mode = m;
    store(MODE_KEY, m);
    els.modeCourses.classList.toggle("active", m === "courses");
    els.modeSites.classList.toggle("active", m === "sites");
    els.modeCourses.setAttribute("aria-pressed", m === "courses");
    els.modeSites.setAttribute("aria-pressed", m === "sites");
    els.search.placeholder = m === "courses"
      ? "Search courses by name, category or citation…"
      : "Search sites by domain or name, or by a course they sell…";
    populateSort();
    render();
  }

  function setView(v) {
    state.view = v;
    store(VIEW_KEY, v);
    els.viewList.classList.toggle("active", v === "list");
    els.viewGrid.classList.toggle("active", v === "grid");
    els.viewList.setAttribute("aria-pressed", v === "list");
    els.viewGrid.setAttribute("aria-pressed", v === "grid");
    render();
  }

  function init() {
    [
      ["search", "search-input"], ["site", "site-select"], ["course", "course-select"], ["group", "group-select"],
      ["topic", "topic-select"], ["category", "category-select"], ["sort", "sort-select"], ["count", "result-count"],
      ["head", "table-head"], ["body", "results-body"], ["grid", "results-grid"], ["wrap", "results-wrap"],
      ["empty", "empty-state"], ["overlay", "modal-overlay"], ["modalTitle", "modal-title"], ["modalBody", "modal-body"],
      ["modeCourses", "mode-courses-btn"], ["modeSites", "mode-sites-btn"], ["viewList", "view-list-btn"],
      ["viewGrid", "view-grid-btn"], ["chips", "active-filters"], ["stats", "header-stats"], ["note", "data-note"],
    ].forEach(function (p) {
      els[p[0]] = document.getElementById(p[1]);
    });

    buildIndexes();
    populateSelects();

    var main = SITES.filter(function (s) { return s.group === "Main domains"; }).length;
    els.stats.innerHTML =
      "<span><strong>" + main + "</strong> main domains</span>" +
      "<span><strong>" + (SITES.length - main) + "</strong> subdomains</span>" +
      "<span><strong>" + COURSES.length + "</strong> unique courses</span>" +
      "<span><strong>" + OFFERS.length + "</strong> listings</span>";
    els.note.textContent = "Data built " + BUILT_ON + ". Regenerate with npm run course-search.";

    var savedView = store(VIEW_KEY);
    if (savedView === "grid" || savedView === "list") state.view = savedView;
    var savedMode = store(MODE_KEY);
    if (savedMode === "sites" || savedMode === "courses") state.mode = savedMode;
    readUrl();

    var debounce;
    els.search.addEventListener("input", function () {
      clearTimeout(debounce);
      debounce = setTimeout(render, 120);
    });
    [els.site, els.course, els.group, els.topic, els.category].forEach(function (sel) {
      sel.addEventListener("change", render);
    });
    els.sort.addEventListener("change", function () {
      state.sort[state.mode] = els.sort.value;
      render();
    });
    els.modeCourses.addEventListener("click", function () { setMode("courses"); });
    els.modeSites.addEventListener("click", function () { setMode("sites"); });
    els.viewList.addEventListener("click", function () { setView("list"); });
    els.viewGrid.addEventListener("click", function (e) {
      if (e.target.closest("a")) return; setView("grid"); });
    document.getElementById("clear-btn").addEventListener("click", function () {
      els.search.value = "";
      [els.site, els.course, els.group, els.topic, els.category].forEach(function (s) { s.value = ""; });
      state.sort[state.mode] = SORT_OPTIONS[state.mode][0][0];
      populateSort();
      render();
    });
    document.getElementById("csv-btn").addEventListener("click", exportCsv);
    els.chips.addEventListener("click", function (e) {
      var b = e.target.closest(".chip");
      if (!b) return;
      els[b.getAttribute("data-key")].value = "";
      render();
    });
    document.getElementById("modal-close").addEventListener("click", closeModal);
    els.overlay.addEventListener("click", function (e) {
      if (e.target === els.overlay) closeModal();
    });
    document.addEventListener("keydown", function (e) {
      if (e.key === "Escape") closeModal();
      if (e.key === "/" && document.activeElement !== els.search && !/input|select|textarea/i.test(document.activeElement.tagName)) {
        e.preventDefault();
        els.search.focus();
      }
    });

    els.viewList.classList.toggle("active", state.view === "list");
    els.viewGrid.classList.toggle("active", state.view === "grid");
    setMode(state.mode);
  }

  document.addEventListener("DOMContentLoaded", init);
})();
